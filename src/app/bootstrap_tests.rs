#[test]
fn an_unrecorded_boundary_is_planned_with_the_conventional_titles() {
    assert_eq!(
        first_boundary_step(FLEET, "prod", &none()),
        BoundaryStep::Create {
            vault: "myapp-api-prod".into(),
            item: "myapp · api · prod values".into()
        }
    );
}

#[test]
fn products_in_one_boundary_group_share_one_planned_boundary() {
    assert_eq!(
        env_plan(CORE, "local", &none()).boundaries[0].products,
        ["api", "web"]
    );
}

#[test]
fn a_product_whose_keys_are_all_personal_needs_no_boundary() {
    assert_eq!(boundary_names(CORE, "local"), ["core"]);
}

#[test]
fn a_from_source_needs_its_boundary() {
    assert_eq!(boundary_names(FROM, "prod"), ["shared", "worker"]);
}

#[test]
fn a_recorded_boundary_in_the_selected_account_is_ok() {
    assert!(matches!(
        first_boundary_step(FLEET, "dev", &none()),
        BoundaryStep::Ok { .. }
    ));
}

#[test]
fn a_recorded_boundary_from_another_account_is_ids_not_in_account() {
    let text = FLEET.replace("vdev0000000000000000000001", OTHER_ACCOUNT);
    assert!(matches!(
        first_boundary_step(&text, "dev", &none()),
        BoundaryStep::IdsNotInAccount { .. }
    ));
}

#[test]
fn rebind_plans_a_new_boundary_in_place_of_a_recorded_one() {
    let rebind = BTreeSet::from(["dev".to_string()]);
    assert!(matches!(
        first_boundary_step(FLEET, "dev", &rebind),
        BoundaryStep::Create { .. }
    ));
}

#[test]
fn rebind_of_an_undeclared_environment_is_refused() {
    let rebind = BTreeSet::from(["qa".to_string()]);
    assert!(plan(&FakeOp::default(), FLEET, "myapp", &rebind).is_err());
}

#[test]
fn a_target_without_state_vault_id_is_planned_with_the_conventional_title() {
    assert_eq!(
        env_plan(FLEET, "prod", &none()).state_vaults[0].step,
        StateStep::Create {
            vault: "myapp-prod-web-state".into()
        }
    );
}

#[test]
fn a_generated_file_is_recognised_by_its_first_line() {
    assert!(is_generated("# Generated by fleetgen; do not edit\n"));
}

#[test]
fn a_hand_written_file_is_not_generated() {
    assert!(!is_generated(FLEET));
}

/// #157: an environment's recorded vault is looked for in that environment's account.
#[test]
fn a_recorded_vault_is_looked_for_in_the_environments_account() {
    let text = FLEET.replace(
        "[environments.dev]\n",
        "[environments.dev]\naccount = \"work.1password.com\"\n",
    );
    let r = crate::runner::fake::FakeRunner::new([crate::runner::Output::success("{}")]);
    let _ = plan(&r, &text, "myapp", &BTreeSet::new());
    assert!(
        r.calls.borrow()[0]
            .env
            .contains(&("OP_ACCOUNT".to_string(), "work.1password.com".to_string()))
    );
}

/// 05.05: a create whose reply never came may have made the vault; it is never "did not
/// create".
#[test]
fn an_unanswered_create_is_create_outcome_unknown() {
    let r = crate::runner::fake::FakeRunner::default();
    r.push_unknown("timeout");
    let e = create(&r, &["vault", "create", "x"], None, CreateKind::Vault, "x").unwrap_err();
    assert_eq!(e.code_str(), "create_outcome_unknown");
}

/// 05.06: the apply finds the vault by its title, so the step is the same command with
/// every flag kept.
#[test]
fn an_unanswered_create_steps_to_the_same_command() {
    let r = crate::runner::fake::FakeRunner::default();
    r.push_unknown("timeout");
    let e = create(&r, &["vault", "create", "x"], None, CreateKind::Vault, "x").unwrap_err();
    let (cause, _) = e.cause().unwrap();
    assert_eq!(
        cause.step(&crate::cause::Invocation::default()).1,
        crate::cause::Next::Rerun
    );
}

/// #159: op's reply decides; "not currently signed in" is a sign-in, never a vault
/// outside the account.
#[test]
fn a_vault_get_op_answers_signed_out_is_op_not_signed_in() {
    let r = crate::runner::fake::FakeRunner::default();
    r.push_with_stderr(
        crate::runner::Output::failure(1),
        "[ERROR] 2026/10/16 00:04:44 You are not currently signed in. Please run `op signin --help` for instructions\n",
    );
    let e = plan(&r, FLEET, "myapp", &none()).unwrap_err();
    assert_eq!(e.code_str(), "op_not_signed_in");
}

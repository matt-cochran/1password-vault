//! The declaration fragment and `generated_by` of a proposal on a generated configuration
//! (#178, FR-52): one atomic test per behaviour, each with exactly one assertion on a
//! public outcome. No test passes a runner: a proposal reads no file and runs no command.

use std::path::PathBuf;

use serde_json::json;

use super::*;
use crate::cause::{Cause, ConfigSource, GivenBy, NotEditable};
use crate::domain::intent;

/// One shared environment `dev` and one product `app` with one key.
const DEV: &str = "[environments.dev]\ntier = \"shared\"\n\
                   boundaries.app = { vault_id = \"vdev0000000000000000000001\", item_id = \"app\" }\n\n\
                   [products.app.keys.EXISTING_KEY]\nkind = \"secret\"\nenvironments = [\"dev\"]\n";

const NEW_KEY: &str = r#"{"kind":"key","key":"NEW_KEY","product":"app","field_kind":"secret"}"#;

/// `DEV` as a generator writes it, under `header`.
fn generated(header: &str) -> String {
    format!("{header}\n{DEV}")
}

/// The proposal of `NEW_KEY` on `DEV` under the header `# generated by fleetgen`.
fn generated_proposal() -> Proposal {
    let intent = intent::parse(NEW_KEY).expect("the intent parses");
    key::propose(
        &generated("# generated by fleetgen; do not edit"),
        &Bindings::default(),
        None,
        &intent,
    )
    .expect("the key proposes")
}

fn fragment_of(p: &Proposal) -> Fragment {
    p.for_generator
        .clone()
        .expect("a generated configuration's proposal carries a fragment")
        .fragment
}

fn file_source() -> ConfigSource {
    ConfigSource::File {
        path: PathBuf::from("cfg/secrets.toml"),
        given_by: GivenBy::Discovered,
    }
}

#[test]
fn a_fragment_holds_only_the_new_key() {
    assert_eq!(
        fragment_of(&generated_proposal()).json,
        json!({"products": {"app": {"keys": {"NEW_KEY": {"kind": "secret"}}}}})
    );
}

#[test]
fn a_fragments_json_equals_its_toml() {
    let f = fragment_of(&generated_proposal());
    let toml: toml::Table = f.toml.parse().expect("the fragment's TOML parses");
    assert_eq!(serde_json::to_value(toml).unwrap(), f.json);
}

#[test]
fn a_fragment_that_loads_carries_no_load_error() {
    assert_eq!(fragment_of(&generated_proposal()).load_error, None);
}

#[test]
fn a_fragment_that_would_not_load_carries_its_load_error() {
    // A key in an environment the file does not declare.
    let after =
        format!("{DEV}\n[products.app.keys.BAD_KEY]\nkind = \"secret\"\nenvironments = [\"qa\"]\n");
    let f = Fragment::between(DEV, &after, &Bindings::default()).unwrap();
    assert_eq!(f.load_error.map(|e| e.code), Some("config_invalid"));
}

#[test]
fn a_fragment_lists_a_removed_declaration_by_its_path() {
    let after = DEV.replace("environments = [\"dev\"]\n", "");
    let f = Fragment::between(DEV, &after, &Bindings::default()).unwrap();
    assert_eq!(
        f.removed,
        vec!["products.app.keys.EXISTING_KEY.environments".to_string()]
    );
}

#[test]
fn a_hand_written_configurations_proposal_has_no_fragment() {
    let intent = intent::parse(NEW_KEY).unwrap();
    let p = key::propose(DEV, &Bindings::default(), None, &intent).unwrap();
    assert_eq!(p.for_generator, None);
}

#[test]
fn a_generated_proposals_text_prints_the_fragment_instead_of_the_diff() {
    assert!(!generated_proposal().render_text().contains("diff:"));
}

#[test]
fn generated_by_names_the_tool_of_a_generated_by_header() {
    assert_eq!(
        crate::app::bootstrap::generated_by(&generated("# generated by fleetgen; do not edit")),
        Some("fleetgen".to_string())
    );
}

#[test]
fn generated_by_names_the_tool_of_an_uppercase_generated_header() {
    assert_eq!(
        crate::app::bootstrap::generated_by(&generated(
            "# GENERATED by fleet_secrets.py from catalog.json — do not edit"
        )),
        Some("fleet_secrets.py".to_string())
    );
}

#[test]
fn a_generated_header_naming_no_tool_has_no_generator() {
    assert_eq!(
        crate::app::bootstrap::generated_by(&generated("# GENERATED — do not edit")),
        None
    );
}

#[test]
fn a_proposal_reports_its_generator() {
    assert_eq!(
        generated_proposal()
            .for_generator
            .and_then(|g| g.generated_by),
        Some("fleetgen".to_string())
    );
}

#[test]
fn the_refusal_names_the_generator() {
    let refusal = generated_refusal(file_source(), &generated_proposal());
    assert!(matches!(
        refusal,
        Cause::ConfigNotEditable {
            reason: NotEditable::Generated { generator: Some(g), .. },
            ..
        } if g.as_path() == std::path::Path::new("fleetgen")
    ));
}

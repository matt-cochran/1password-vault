//! `opv propose` (design Part V, row `propose-key`): the contract diff a categorical intent
//! implies, with the relaxations it makes against the default branch listed first, the
//! categorical questions it asks, and a content-addressed plan id.
//!
//! Pure: a proposal reads no file and runs no command. Only [`key::write`] touches the
//! contract file, and only when a caller asks it to.

pub mod key;
pub mod setup;
pub mod structure;
pub mod target;

use serde::Serialize;

pub use crate::cause::{Fragment, LoadError};
use crate::config::bindings::Bindings;
use crate::domain::relaxation::{Relaxation, RelaxationKind};
use crate::error::Error;

/// One categorical question the plan asks the person, by environment
/// (`a value, or except?` for a production-tier environment).
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct Question {
    /// The environment the question is about.
    pub env: String,
    /// The question itself, a fixed sentence.
    pub ask: String,
}

/// A proposed contract change: the relaxations it makes against the default branch
/// (listed first), the contract diff, the questions it asks, and a content-addressed
/// `plan_id`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct Proposal {
    /// The intent kind (`key`, `env` or `retire`).
    pub kind: &'static str,
    /// The relaxations of the proposed contract against the default branch, listed first.
    #[serde(serialize_with = "relaxations_json")]
    pub relaxations: Vec<Relaxation>,
    /// A unified line diff of the contract file: names and rules only, never a value.
    pub diff: String,
    /// The categorical questions the plan asks, by environment.
    pub questions: Vec<Question>,
    /// Lowercase hex SHA-256 of the kind and the proposed contract text.
    pub plan_id: String,
    /// The proposed contract text itself (names and rules only, never an id or a value):
    /// what `--write` saves. Not part of the wire document, which carries the diff.
    #[serde(skip)]
    pub contract_after: String,
    /// On a generated configuration (FR-52, #178): the generator that writes it and the
    /// declaration fragment it must emit. Flattened into the wire document as
    /// `generated_by` and `fragment`; absent for a configuration opv edits itself.
    #[serde(flatten)]
    pub for_generator: Option<ForGenerator>,
}

/// What a generated configuration's generator must emit for a proposal (#178): the tool the
/// file's first line names, and the validated declaration fragment.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct ForGenerator {
    /// The generator the first line names (`# generated by <tool>`, `# GENERATED by <tool>
    /// …`); `null` when the header names none.
    pub generated_by: Option<String>,
    /// The declarations the proposal adds or changes, and nothing else.
    pub fragment: Fragment,
}

impl Fragment {
    /// The fragment that takes `before` to `after` (both contract texts, no ids), judged by
    /// merging it into `before` with `bindings` and loading the result as it will load once
    /// the structural plan records the ids still missing (a declaration's own trial).
    pub fn between(before: &str, after: &str, bindings: &Bindings) -> Result<Fragment, Error> {
        let before = table(before)?;
        let after = table(after)?;
        let mut removed = Vec::new();
        let changed = changed(&before, &after, "", &mut removed);
        let toml = toml::to_string(&changed).map_err(|_| bug("the fragment did not serialize"))?;
        let json =
            serde_json::to_value(&changed).map_err(|_| bug("the fragment did not serialize"))?;
        let load_error = load_error(before, &changed, &removed, bindings);
        Ok(Fragment {
            toml,
            json,
            removed,
            load_error,
        })
    }
}

/// The [`ForGenerator`] of a proposal that takes `contract_text` to `proposed`: `None` when
/// `contract_text` is not generated (opv edits it itself). `refused`: the error the
/// proposal's own validation raised for `proposed`, which the fragment then carries as its
/// load error (the error the generated file would raise once the generator emits it).
pub fn for_generator(
    contract_text: &str,
    proposed: &str,
    bindings: &Bindings,
    refused: Option<&Error>,
) -> Result<Option<ForGenerator>, Error> {
    if !crate::app::bootstrap::is_generated(contract_text) {
        return Ok(None);
    }
    let mut fragment = Fragment::between(contract_text, proposed, bindings)?;
    if let Some(e) = refused {
        fragment.load_error = Some(load_error_of(e));
    }
    Ok(Some(ForGenerator {
        generated_by: crate::app::bootstrap::generated_by(contract_text),
        fragment,
    }))
}

/// The validation of a proposed contract on `contract_text`: `Ok(Some(fleet))` when it
/// loads; on a generated configuration, `Ok(None)` and the error kept in `refused` for the
/// fragment (#178: the generator's author sees the error its file would raise); on a
/// hand-written one, the error itself (opv never writes a file that would not load).
pub fn validated<T>(
    contract_text: &str,
    loaded: Result<T, Error>,
    refused: &mut Option<Error>,
) -> Result<Option<T>, Error> {
    match loaded {
        Ok(v) => Ok(Some(v)),
        Err(e) if crate::app::bootstrap::is_generated(contract_text) => {
            *refused = Some(e);
            Ok(None)
        }
        Err(e) => Err(e),
    }
}

/// A load error as a fragment reports it: its stable code and its message.
fn load_error_of(e: &Error) -> LoadError {
    LoadError {
        code: e.code_str(),
        message: e.text(),
    }
}

fn bug(site: &'static str) -> Error {
    crate::cause::Cause::Bug { site }.into()
}

fn table(text: &str) -> Result<toml::Table, Error> {
    text.parse::<toml::Table>()
        .map_err(|_| bug("propose: a contract text did not parse as TOML"))
}

/// What `after` adds to or changes in `before`, under the dotted path `at`; the paths
/// `before` holds and `after` does not go to `removed`.
fn changed(
    before: &toml::Table,
    after: &toml::Table,
    at: &str,
    removed: &mut Vec<String>,
) -> toml::Table {
    let mut out = toml::Table::new();
    for (k, v) in after {
        match (before.get(k), v) {
            (Some(toml::Value::Table(b)), toml::Value::Table(a)) => {
                let sub = changed(b, a, &dotted(at, k), removed);
                if !sub.is_empty() {
                    out.insert(k.clone(), toml::Value::Table(sub));
                }
            }
            (Some(b), a) if b == a => {}
            _ => {
                out.insert(k.clone(), v.clone());
            }
        }
    }
    removed.extend(
        before
            .keys()
            .filter(|k| !after.contains_key(*k))
            .map(|k| dotted(at, k)),
    );
    out
}

/// `key` under the dotted path `at`, quoted when it is not a bare TOML key.
fn dotted(at: &str, key: &str) -> String {
    let bare = !key.is_empty()
        && key
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '-');
    let key = if bare {
        key.to_string()
    } else {
        format!("{key:?}")
    };
    if at.is_empty() {
        key
    } else {
        format!("{at}.{key}")
    }
}

/// `fragment` merged into `base` (its tables into the base's, its other values replacing),
/// without the `removed` paths.
fn merged(mut base: toml::Table, fragment: &toml::Table) -> toml::Table {
    for (k, v) in fragment {
        match (base.get_mut(k), v) {
            (Some(toml::Value::Table(b)), toml::Value::Table(f)) => {
                *b = merged(std::mem::take(b), f);
            }
            _ => {
                base.insert(k.clone(), v.clone());
            }
        }
    }
    base
}

fn remove(table: &mut toml::Table, path: &[String]) {
    match path {
        [] => {}
        [last] => {
            table.remove(last);
        }
        [first, rest @ ..] => {
            if let Some(toml::Value::Table(t)) = table.get_mut(first) {
                remove(t, rest);
            }
        }
    }
}

/// The error the file `base` with `fragment` merged in (and `removed` taken out) would
/// raise, as the loader reports it; `None` when it loads.
fn load_error(
    base: toml::Table,
    fragment: &toml::Table,
    removed: &[String],
    bindings: &Bindings,
) -> Option<LoadError> {
    let mut whole = merged(base, fragment);
    for path in removed {
        remove(&mut whole, &split_dotted(path));
    }
    let loaded = toml::to_string(&whole)
        .map_err(|_| bug("the merged fragment did not serialize"))
        .and_then(|text| {
            crate::app::structure::trial_text(&crate::config::bindings::merge(&text, bindings))
        })
        .and_then(|text| crate::config::parse(&text));
    loaded.err().as_ref().map(load_error_of)
}

/// A dotted path from [`dotted`] back into its keys.
fn split_dotted(path: &str) -> Vec<String> {
    let mut keys = Vec::new();
    let mut rest = path;
    while !rest.is_empty() {
        if let Some(quoted) = rest.strip_prefix('"') {
            // A quoted key: up to its closing, unescaped quote.
            let mut end = 0;
            let mut escaped = false;
            for (i, c) in quoted.char_indices() {
                match c {
                    '\\' if !escaped => escaped = true,
                    '"' if !escaped => {
                        end = i;
                        break;
                    }
                    _ => escaped = false,
                }
            }
            let raw = &rest[..end + 2];
            keys.push(serde_json::from_str(raw).unwrap_or_else(|_| raw.to_string()));
            rest = rest[end + 2..].strip_prefix('.').unwrap_or_default();
        } else {
            let (key, tail) = rest.split_once('.').unwrap_or((rest, ""));
            keys.push(key.to_string());
            rest = tail;
        }
    }
    keys
}

impl Proposal {
    /// The proposal as text, with the relaxations listed before the diff.
    pub fn render_text(&self) -> String {
        let mut out = String::new();
        if self.relaxations.is_empty() {
            out.push_str("relaxations: none\n");
        } else {
            out.push_str("relaxations:\n");
            for r in &self.relaxations {
                let at = match &r.env {
                    Some(env) => format!("{}/{} ({env})", r.product, r.key),
                    None => format!("{}/{}", r.product, r.key),
                };
                out.push_str(&format!("  {at}: {}\n", r.reason));
            }
        }
        match &self.for_generator {
            // A generated configuration: the fragment its generator must emit, not a
            // whole-file diff (#178).
            Some(g) => g.render_into(&mut out),
            None => {
                out.push_str("diff:\n");
                out.push_str(&self.diff);
                if !self.diff.is_empty() && !self.diff.ends_with('\n') {
                    out.push('\n');
                }
            }
        }
        for q in &self.questions {
            out.push_str(&format!("{}: {}\n", q.env, q.ask));
        }
        out.push_str(&format!("plan_id: {}\n", self.plan_id));
        out
    }
}

impl ForGenerator {
    /// `generated_by:`, the fragment's TOML under `fragment:`, the removed paths and the
    /// load error (or `none`).
    fn render_into(&self, out: &mut String) {
        let by = self
            .generated_by
            .as_deref()
            .unwrap_or("(the header names none)");
        out.push_str(&format!("generated_by: {by}\n"));
        out.push_str("fragment:\n");
        out.push_str(&self.fragment.toml);
        if !self.fragment.toml.is_empty() && !self.fragment.toml.ends_with('\n') {
            out.push('\n');
        }
        for path in &self.fragment.removed {
            out.push_str(&format!("removed: {path}\n"));
        }
        match &self.fragment.load_error {
            Some(e) => out.push_str(&format!("load_error: {}: {}\n", e.code, e.message)),
            None => out.push_str("load_error: none\n"),
        }
    }
}

/// FR-52 (#184): opv never edits a generated configuration (one whose first line starts
/// with `# generated`); its generator is, which the refusal names when the first line does
/// (#178). The refusal a `--write` of `proposal` meets on the configuration `source`: it
/// carries the proposal's declaration fragment, what the generator must emit instead (with
/// the error the file would raise), and steps to `opv propose structure` once the
/// generator emits it.
pub fn generated_refusal(
    source: crate::cause::ConfigSource,
    proposal: &Proposal,
) -> crate::cause::Cause {
    crate::cause::Cause::ConfigNotEditable {
        source,
        reason: crate::cause::NotEditable::Generated {
            generator: proposal
                .for_generator
                .as_ref()
                .and_then(|g| g.generated_by.clone())
                .or_else(|| crate::app::bootstrap::generated_by(&proposal.contract_after))
                .map(std::path::PathBuf::from),
            fragment: proposal.for_generator.as_ref().map(|g| g.fragment.clone()),
        },
    }
}

/// The `next` of a read-only proposal on a generated configuration (the CLI's and the MCP
/// tool's alike): never the `--write` that [`generated_refusal`] refuses, but that
/// refusal's own step under `inv`, the structure once the generator emits the change.
pub fn generated_next(
    source: crate::cause::ConfigSource,
    proposal: &Proposal,
    inv: &crate::cause::Invocation,
) -> serde_json::Value {
    let next = generated_refusal(source, proposal).step(inv).1;
    crate::cause::render::next_value(&next, inv)
}

/// The line a read-only proposal on a generated configuration prints before its `Next:`.
pub const GENERATED_ROUTE: &str = "generated: the configuration's generator emits this fragment, opv never edits the configuration; once the generator emits it, opv propose structure, then opv apply, returns the ids (generator_ids) for the generator to record";

/// Serialize the relaxations (which carry no `Serialize` of their own) as objects, so the
/// wire form names the product, key, environment, kind and fixed reason only.
fn relaxations_json<S>(relaxations: &[Relaxation], serializer: S) -> Result<S::Ok, S::Error>
where
    S: serde::Serializer,
{
    use serde::ser::SerializeSeq;
    let mut seq = serializer.serialize_seq(Some(relaxations.len()))?;
    for r in relaxations {
        seq.serialize_element(&RelaxationView {
            product: &r.product,
            key: &r.key,
            env: r.env.as_deref(),
            kind: relaxation_kind_name(r.kind),
            reason: r.reason,
        })?;
    }
    seq.end()
}

#[derive(Serialize)]
struct RelaxationView<'a> {
    product: &'a str,
    key: &'a str,
    #[serde(skip_serializing_if = "Option::is_none")]
    env: Option<&'a str>,
    kind: &'a str,
    reason: &'a str,
}

/// One relaxation as its wire object: product, key, environment, kind and fixed reason.
pub fn relaxation_json(r: &Relaxation) -> serde_json::Value {
    serde_json::to_value(RelaxationView {
        product: &r.product,
        key: &r.key,
        env: r.env.as_deref(),
        kind: relaxation_kind_name(r.kind),
        reason: r.reason,
    })
    .unwrap_or(serde_json::Value::Null)
}

/// The wire name of a relaxation kind.
fn relaxation_kind_name(kind: RelaxationKind) -> &'static str {
    match kind {
        RelaxationKind::AllowSameValueAdded => "allow_same_value_added",
        RelaxationKind::ExceptProduction => "except_production",
        RelaxationKind::PresenceNarrowed => "presence_narrowed",
        RelaxationKind::RuleRemoved => "rule_removed",
        RelaxationKind::SecretToConfig => "secret_to_config",
    }
}


//! Behaviour of the shape catalog (deliverable `catalog`): one observable outcome per
//! test, one test per listed shape. Everything here goes through the public catalog API.

use super::*;
use crate::app::generate::recipe;
use crate::domain::KeySpec;

/// A key spec carrying only the shape's rules, so `recipe` sees nothing else.
fn spec(rules: Rules) -> KeySpec {
    KeySpec {
        kind: Kind::Secret,
        environments: Some(Vec::new()),
        except: Default::default(),
        rules,
        immutable: false,
        guidance: String::new(),
        from: None,
        personal: false,
        allow_same_value: false,
        file: None,
        roles: None,
        value_source: None,
        expires: None,
        lifecycle: Default::default(),
    }
}

// --- One test per listed shape -------------------------------------------------

#[test]
fn stripe_secret_maps_to_its_rules_and_suggestion() {
    assert_eq!(
        lookup("stripe_secret"),
        Some(&Shape {
            name: "stripe_secret",
            rules: Rules {
                prefix: Some("sk_".to_owned()),
                ..Rules::default()
            },
            kind: Kind::Secret,
            source: Source::Person,
            scope: Scope::Shared,
            guidance: "Stripe Dashboard > Developers > API keys; the secret key starts sk_.",
            dated: Dated {
                date: "2026-10-18",
                source: "Stripe API reference, API keys",
            },
        })
    );
}


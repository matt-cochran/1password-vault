// --- Catalog-wide properties ---------------------------------------------------

#[test]
fn lookup_returns_none_for_an_unknown_name() {
    assert_eq!(lookup("no_such_shape"), None);
}

#[test]
fn names_are_sorted() {
    let names = names();
    assert!(names.windows(2).all(|pair| pair[0] < pair[1]));
}

#[test]
fn names_cover_every_documented_shape() {
    let documented = [
        "stripe_secret",
        "openai_key",
        "pem_private_key",
        "https_url",
        "url",
        "base64_bytes_32",
        "hex_bytes_32",
        "email_list",
    ];
    assert!(documented.iter().all(|name| lookup(name).is_some()));
}

#[test]
fn every_shape_name_matches_the_lowercase_grammar() {
    assert!(names().iter().all(|name| {
        name.starts_with(|c: char| c.is_ascii_lowercase())
            && name
                .chars()
                .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
    }));
}

#[test]
fn every_guidance_is_a_single_line() {
    assert!(catalog().iter().all(|shape| !shape.guidance.contains('\n')));
}

#[test]
fn every_guidance_is_at_most_two_hundred_characters() {
    assert!(
        catalog()
            .iter()
            .all(|shape| shape.guidance.chars().count() <= 200)
    );
}

#[test]
fn every_entry_has_a_date() {
    assert!(catalog().iter().all(|shape| !shape.dated.date.is_empty()));
}

#[test]
fn every_entry_names_a_public_source() {
    assert!(catalog().iter().all(|shape| !shape.dated.source.is_empty()));
}

#[test]
fn generated_shapes_are_ones_the_generator_can_make() {
    assert!(
        catalog()
            .iter()
            .filter(|shape| shape.source == Source::Generated)
            .all(|shape| recipe("p", "KEY", "env", &spec(shape.rules.clone())).is_ok())
    );
}
